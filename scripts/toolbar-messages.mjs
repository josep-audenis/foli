// Collects every string of the toolbar (packages/react/src/FoliToolbar.tsx) into
// `toolbarMessages` (packages/react/src/messages.ts): the `t("…")` and `tr("…")` calls, and the
// built-in items', menus', palettes', tabs' and dialogs' labels. With `--check` (in `pnpm check`)
// it fails when the list is not up to date; without it, it writes the list.
import { readFileSync, writeFileSync } from "node:fs";

const source = "packages/react/src/FoliToolbar.tsx";
const target = "packages/react/src/messages.ts";
const code = readFileSync(source, "utf8")
  .split("\n")
  // Comments are not shown.
  .filter((line) => !/^\s*(\*|\/\/|\/\*)/.test(line))
  .join("\n");

/** A double-quoted string literal (its text in group 1). */
const string = '"((?:[^"\\\\]|\\\\.)*)"';
const patterns = [
  // t("…") and tr("…"), alone or with values
  new RegExp(`\\btr?\\(\\s*${string}`, "g"),
  // labels, visible texts and color names of the built-ins
  new RegExp(`\\b(?:label|text|name):\\s*${string}`, "g"),
  // the navigation menu's entries: item("key", "Label")
  new RegExp(`\\bitem\\(\\s*"[^"]*",\\s*${string}`, "g"),
  // mark("bold", "Bold", "B") and align("start", "Align left", …)
  new RegExp(`\\b(?:mark|align)\\(\\s*"[^"]*",\\s*${string}`, "g"),
  new RegExp(`\\bmark\\(\\s*"[^"]*",\\s*"[^"]*",\\s*${string}`, "g"),
  // the ribbon's group captions: group("Font", …)
  new RegExp(`\\bgroup\\(\\s*${string}`, "g"),
  // a letter for an icon (A for text color); symbols (•, №) are not words
  /\bicon:\s*"([A-Z])"/g,
  // [value, label] pairs (section starts, note formats)
  new RegExp(`\\[\\s*"[^"]*",\\s*${string}\\s*\\]`, "g"),
];
const found = new Set();
for (const pattern of patterns)
  for (const match of code.matchAll(pattern)) found.add(JSON.parse(`"${match[1]}"`));
// The page setup fields' labels (`width: "Page width (cm)",` in SETUP_LABELS).
const from = code.indexOf("const SETUP_LABELS");
for (const match of code.slice(from, code.indexOf("};", from)).matchAll(new RegExp(string, "g")))
  found.add(JSON.parse(`"${match[1]}"`));

// Shown text starts with a capital, a digit or a symbol (`1, 2, 3`, `*, †, ‡`), or is a list of
// letters (`a, b, c`); keys and values (`"nextPage"`, `"#c00000"`) are not.
// Word's Change Case entries show their own case.
const CASES = new Set(["lowercase", "tOGGLE cASE"]);
const shown = (text) => /^[A-Z0-9*…]/.test(text) || /^[a-z], [a-z]/.test(text) || CASES.has(text);
// By code point: the same order on every machine.
const list = [...found].filter(shown).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

// Text the toolbar would show without `t(…)`: a literal in JSX or in an attribute people read.
const raw = [
  ...code.matchAll(/\b(?:aria-label|title|alt|placeholder)="([A-Za-z][^"]*)"/g),
  // an element's text before its closing tag: `<p>Text</p>`
  ...code.matchAll(/>[ \t]*([A-Za-z][^<>{}\n]*?)[ \t]*<\//g),
  // a line of JSX text on its own, between tags
  ...code.matchAll(/^[ \t]+([A-Z][A-Za-z ,.…'’()-]*[a-z.…)])[ \t]*$/gm),
].map((match) => match[1]);
if (raw.length) {
  console.error(
    `${source}: text shown without t(…): ${raw.map((text) => JSON.stringify(text)).join(", ")}`,
  );
  process.exit(1);
}

const body = list.map((text) => `  ${JSON.stringify(text)},`).join("\n");
const now = readFileSync(target, "utf8");
const next = now.replace(
  /(export const toolbarMessages = \[\n)[\s\S]*?(\] as const;)/,
  `$1  // @generated by scripts/toolbar-messages.mjs from FoliToolbar.tsx: run it after a change there.\n${body}\n$2`,
);
if (!/export const toolbarMessages = \[\n[\s\S]*?\] as const;/.test(now)) {
  console.error(`${target}: no \`export const toolbarMessages = [ … ] as const;\` to fill in.`);
  process.exit(1);
}
if (process.argv.includes("--check")) {
  if (next !== now) {
    console.error(
      `${target}: toolbarMessages is not up to date with ${source}: run \`node scripts/toolbar-messages.mjs\`.`,
    );
    process.exit(1);
  }
  console.log(`toolbarMessages: ${list.length} strings, up to date`);
} else {
  writeFileSync(target, next);
  console.log(`toolbarMessages: ${list.length} strings written`);
}
